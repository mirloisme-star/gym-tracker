// Replaces the program with a template's days. Exercises are reused by name, so history stays linked.
export function applyTemplate(template) {
  state.days = template.days.map(([name, rows]) => ({
    id: uid(),
    name,
    weekdays: [],
    items: rows.map(({ name: exName, muscle, kind, ...item }) => ({
      exerciseId: findOrCreateExercise(exName, muscle, kind).id,
      note: '',
      ...item,
    })),
  }));
  saveMeta('days');
  saveMeta('exercises');
}
